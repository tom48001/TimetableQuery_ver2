import pool from '../src/db.js';
import { normalizedTeacherName } from '../src/utils/teacherRoster.js';
import { isAutoGeneratedTeacherCode } from '../src/utils/timetableTeacherMatch.js';

// One-off helper for databases where earlier imports created duplicate teacher
// rows for the same person (mixed-case roster row + uppercase timetable row).
//
// Default is a dry run that only prints what would happen. Re-run with --apply
// to execute. Identical names can be merged automatically; anything that only
// looks similar is listed for a human to confirm, because identical names can
// belong to different people. Use --merge-ids 保留ID,移除ID to merge a pair you
// have confirmed manually.

const APPLY = process.argv.includes('--apply');
const MANUAL_MERGES = process.argv.filter(arg => /^--merge-ids=\d+,\d+$/.test(arg))
  .map(arg => arg.replace('--merge-ids=', '').split(',').map(Number));
const RELATED_TABLES = ['teacher_subject', 'nomination', 'prefect_nomination', 'BLA', 'learning_goal_record'];

async function relatedCounts(conn, teacherId) {
  const counts = {};
  for (const table of RELATED_TABLES) {
    const [rows] = await conn.query(`SELECT COUNT(*) AS count FROM ${table} WHERE teacher_id = ?`, [teacherId]);
    counts[table] = Number(rows[0].count);
  }
  return counts;
}

async function buildGroups(conn) {
  const [teachers] = await conn.query(`
    SELECT t.teacher_id, t.user_id, t.teacher_code, t.teacher_name, t.source_login,
           t.english_name, t.chinese_name, t.status,
           u.email AS linked_email,
           (SELECT COUNT(*) FROM timetable tt WHERE tt.teacher_id = t.teacher_id) AS lesson_count
    FROM teacher t LEFT JOIN user u ON u.user_id = t.user_id
    ORDER BY t.teacher_id
  `);
  const groups = new Map();
  for (const teacher of teachers) {
    const key = normalizedTeacherName(teacher.teacher_name);
    if (!key) continue;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(teacher);
  }
  return [...groups.entries()]
    .filter(([, members]) => members.length > 1)
    .map(([name, members]) => ({ name, members }));
}

function pickSurvivor(members) {
  const withLessons = members.filter(member => member.lesson_count > 0);
  if (withLessons.length === 1) return withLessons[0];
  if (withLessons.length > 1) return null;
  const withAccount = members.filter(member => member.user_id !== null);
  if (withAccount.length === 1) return withAccount[0];
  const withRealCode = members.filter(member => !isAutoGeneratedTeacherCode(member.teacher_code));
  if (withRealCode.length === 1) return withRealCode[0];
  return null;
}

function describe(teacher) {
  return `#${teacher.teacher_id} code=${teacher.teacher_code || 'NULL'} name=${teacher.teacher_name}` +
    ` lessons=${teacher.lesson_count} login=${teacher.source_login || '-'}` +
    ` email=${teacher.linked_email || '-'}`;
}

function isAllUpper(name) {
  return String(name || '') === normalizedTeacherName(name);
}

async function mergeOne(conn, survivor, loser) {
  if (loser.lesson_count > 0) return `略過：#${loser.teacher_id} 仍有課堂，請人工處理`;
  const counts = await relatedCounts(conn, loser.teacher_id);
  const busy = Object.entries(counts).filter(([, count]) => count > 0);
  if (busy.length) return `略過：#${loser.teacher_id} 仍有關聯資料（${busy.map(([table, count]) => `${table}:${count}`).join(', ')}）`;
  if (loser.user_id !== null && survivor.user_id !== null && loser.user_id !== survivor.user_id) {
    return `略過：#${survivor.teacher_id} 與 #${loser.teacher_id} 各自連結不同帳戶`;
  }

  if (!APPLY) return 'planned';
  await conn.query('UPDATE teacher SET user_id = NULL WHERE teacher_id = ?', [loser.teacher_id]);
  if (survivor.user_id === null && loser.user_id !== null) {
    await conn.query('UPDATE teacher SET user_id = ? WHERE teacher_id = ?', [loser.user_id, survivor.teacher_id]);
    survivor.user_id = loser.user_id;
  }
  const fills = {};
  for (const column of ['source_login', 'english_name', 'chinese_name']) {
    if (survivor[column] === null && loser[column] !== null) fills[column] = loser[column];
  }
  if (isAutoGeneratedTeacherCode(survivor.teacher_code) && !isAutoGeneratedTeacherCode(loser.teacher_code)) {
    fills.teacher_code = loser.teacher_code;
  }
  // Prefer a mixed-case display name over an ALL-CAPS import label.
  if (isAllUpper(survivor.teacher_name) && !isAllUpper(loser.teacher_name)) {
    fills.teacher_name = loser.teacher_name;
    if (loser.english_name && fills.english_name === undefined) fills.english_name = loser.english_name;
  }
  if (Object.keys(fills).length) {
    await conn.query(`UPDATE teacher SET ${Object.keys(fills).map(column => `${column} = ?`).join(', ')} WHERE teacher_id = ?`,
      [...Object.values(fills), survivor.teacher_id]);
  }
  await conn.query('DELETE FROM teacher WHERE teacher_id = ?', [loser.teacher_id]);
  return 'merged';
}

async function manualMerge(conn, keepId, dropId) {
  const [rows] = await conn.query('SELECT * FROM teacher WHERE teacher_id IN (?, ?)', [keepId, dropId]);
  const survivor = rows.find(row => row.teacher_id === keepId);
  const loser = rows.find(row => row.teacher_id === dropId);
  if (!survivor || !loser) return console.log(`--merge-ids ${keepId},${dropId}: 找不到老師，略過`);
  // Re-point the loser's timetable rows first if any.
  if (loser.lesson_count !== undefined) { /* placeholder, recalc below */ }
  const [lessonRows] = await conn.query('SELECT COUNT(*) c FROM timetable WHERE teacher_id = ?', [dropId]);
  if (Number(lessonRows[0].c) > 0) {
    const [conflicts] = await conn.query(`
      SELECT COUNT(*) c FROM timetable a JOIN timetable b
        ON a.teacher_id = ? AND b.teacher_id = ? AND a.day_of_week = b.day_of_week AND a.period_id = b.period_id
    `, [keepId, dropId]);
    if (Number(conflicts[0].c) > 0) return console.log(`--merge-ids ${keepId},${dropId}: 雙方在同一時段都有課堂，無法自動合併`);
    await conn.query('UPDATE timetable SET teacher_id = ? WHERE teacher_id = ?', [keepId, dropId]);
  }
  const result = await mergeOne(conn, survivor, { ...loser, lesson_count: 0 });
  console.log(`--merge-ids ${keepId},${dropId}: ${result}`);
}

async function main() {
  const conn = await pool.getConnection();
  try {
    for (const [keepId, dropId] of MANUAL_MERGES) await manualMerge(conn, keepId, dropId);
    if (MANUAL_MERGES.length) return;

    const groups = await buildGroups(conn);
    if (!groups.length) {
      console.log('沒有找到同名老師群組，無需合併。');
    } else {
      console.log(`找到 ${groups.length} 個同名老師群組。模式：${APPLY ? '執行合併' : '預覽（加 --apply 才會寫入資料庫）'}\n`);
      let merged = 0; let planned = 0; let skipped = 0;
      for (const group of groups) {
        console.log(`群組「${group.name}」`);
        group.members.forEach(member => console.log(`  ${describe(member)}`));
        const survivor = pickSurvivor(group.members);
        if (!survivor) {
          skipped++;
          console.log('  ✖ 略過：無法自動判斷保留哪一筆（多位老師有課堂/帳戶/代號），請人工處理\n');
          continue;
        }
        const losers = group.members.filter(member => member.teacher_id !== survivor.teacher_id);
        let allOk = true;
        for (const loser of losers) {
          const result = await mergeOne(conn, survivor, loser);
          if (result === 'planned') {
            console.log(`  → 將合併：保留 #${survivor.teacher_id}，移除 #${loser.teacher_id}`);
          } else if (result === 'merged') {
            console.log(`  ✔ 已合併：保留 #${survivor.teacher_id}，移除 #${loser.teacher_id}`);
          } else {
            allOk = false;
            console.log(`  ✖ ${result}`);
          }
        }
        if (allOk) { APPLY ? merged++ : planned++; } else skipped++;
        console.log('');
      }
      console.log(`完成：${APPLY ? `合併 ${merged}` : `計劃合併 ${planned}`} 組，略過 ${skipped} 組。`);
    }

    // Review list: lesson-less teachers whose surname matches a lesson teacher
    // but whose full name differs — possible same person, needs human eyes.
    const [teachers] = await conn.query(`
      SELECT t.teacher_id, t.teacher_code, t.teacher_name,
             (SELECT COUNT(*) FROM timetable tt WHERE tt.teacher_id = t.teacher_id) AS lesson_count
      FROM teacher t
    `);
    const withLessons = teachers.filter(t => t.lesson_count > 0);
    const withoutLessons = teachers.filter(t => t.lesson_count === 0);
    const taken = new Set(withLessons.map(t => normalizedTeacherName(t.teacher_name)));
    const review = [];
    for (const idle of withoutLessons) {
      const key = normalizedTeacherName(idle.teacher_name);
      if (taken.has(key)) continue;
      const surname = key.split(' ')[0];
      const candidates = withLessons
        .filter(busy => normalizedTeacherName(busy.teacher_name).startsWith(surname) ||
                        key.startsWith(normalizedTeacherName(busy.teacher_name).split(' ')[0]))
        .map(busy => `#${busy.teacher_id} ${busy.teacher_name}`);
      if (candidates.length) review.push(`#${idle.teacher_id} ${idle.teacher_name}（${idle.teacher_code || '無代號'}）→ 可能同一人：${candidates.join('、')}`);
    }
    if (review.length) {
      console.log(`\n=== 需人工確認（名稱不完全相同，不會自動合併）===`);
      review.forEach(line => console.log(' ' + line));
      console.log('確認後可用 --merge-ids=保留ID,移除ID 合併（例如 --apply --merge-ids=100,15，可重複使用）');
    }
  } finally {
    conn.release();
    await pool.end();
  }
}

main().catch(error => {
  console.error('合併程式失敗：', error);
  process.exitCode = 1;
});
