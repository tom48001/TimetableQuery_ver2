import test from 'node:test';
import assert from 'node:assert/strict';
import { isAutoGeneratedTeacherCode, resolveTimetableTeachers } from '../src/utils/timetableTeacherMatch.js';

const existingTeachers = [
  { teacher_id: 1, teacher_code: 'STAFF-abc', teacher_name: 'Chan Tai Man', english_name: 'Chan Tai Man', chinese_name: '陳大文' },
  { teacher_id: 2, teacher_code: 'CWK', teacher_name: 'CHAN WAI KIT', english_name: null, chinese_name: null },
  { teacher_id: 3, teacher_code: 'STAFF-xy', teacher_name: 'Lee Siu Ming', english_name: 'Lee Siu Ming', chinese_name: null },
  { teacher_id: 4, teacher_code: 'LSM', teacher_name: 'LEE SIU MING', english_name: 'LEE SIU MING', chinese_name: null }
];

test('creates a teacher only when neither code nor name matches anyone', () => {
  const nameByCode = new Map([['NEW1', 'Brand New Teacher']]);
  const result = resolveTimetableTeachers({
    missingCodes: [{ teacher_code: 'NEW1' }],
    nameByCode,
    existingTeachers
  });
  assert.deepEqual(result.create, [{ code: 'NEW1', name: 'Brand New Teacher' }]);
  assert.deepEqual(result.adopt, []);
  assert.deepEqual(result.conflicts, []);
});

test('adopts the timetable abbreviation onto the same-name teacher with a placeholder code', () => {
  const nameByCode = new Map([['CTM', 'CHAN TAI MAN']]);
  const result = resolveTimetableTeachers({
    missingCodes: [{ teacher_code: 'CTM' }],
    nameByCode,
    existingTeachers
  });
  assert.deepEqual(result.adopt, [{ code: 'CTM', teacherId: 1, name: 'CHAN TAI MAN' }]);
  assert.deepEqual(result.create, []);
  assert.deepEqual(result.conflicts, []);
});

test('never overrides a real existing code and reports it as a conflict', () => {
  const nameByCode = new Map([['LSM2', 'LEE SIU MING']]);
  const result = resolveTimetableTeachers({
    missingCodes: [{ teacher_code: 'LSM2' }],
    nameByCode,
    existingTeachers: existingTeachers.filter(teacher => teacher.teacher_id !== 3)
  });
  assert.equal(result.adopt.length, 0);
  assert.equal(result.create.length, 0);
  assert.equal(result.conflicts.length, 1);
  assert.equal(result.conflicts[0].reason, 'existing-code-mismatch');
});

test('identical names on two teachers stay unresolved instead of guessing', () => {
  const ambiguous = [
    { teacher_id: 5, teacher_code: 'STAFF-a', teacher_name: 'WONG WAI', english_name: 'Wong Wai', chinese_name: null },
    { teacher_id: 6, teacher_code: 'STAFF-b', teacher_name: 'WONG WAI', english_name: 'Wong Wai', chinese_name: null }
  ];
  const result = resolveTimetableTeachers({
    missingCodes: [{ teacher_code: 'WONG1' }],
    nameByCode: new Map([['WONG1', 'Wong Wai']]),
    existingTeachers: ambiguous
  });
  assert.equal(result.conflicts.length, 1);
  assert.equal(result.conflicts[0].reason, 'ambiguous-name');
  assert.equal(result.conflicts[0].candidates.length, 2);
});

test('two abbreviations for the same person are flagged instead of double-adopting', () => {
  const nameByCode = new Map([['CTM1', 'Chan Tai Man'], ['CTM2', 'CHAN TAI MAN']]);
  const result = resolveTimetableTeachers({
    missingCodes: [{ teacher_code: 'CTM1' }, { teacher_code: 'CTM2' }],
    nameByCode,
    existingTeachers
  });
  assert.equal(result.adopt.length, 1);
  assert.equal(result.conflicts.length, 1);
  assert.equal(result.conflicts[0].reason, 'duplicate-code-mapping');
});

test('isAutoGeneratedTeacherCode recognises placeholders only', () => {
  assert.equal(isAutoGeneratedTeacherCode('STAFF-abc-123'), true);
  assert.equal(isAutoGeneratedTeacherCode(''), true);
  assert.equal(isAutoGeneratedTeacherCode(null), true);
  assert.equal(isAutoGeneratedTeacherCode('CWK'), false);
});
